import fs from "node:fs"; import os from "node:os"; import path from "node:path";
import puppeteer from "puppeteer-core";
const BASE = process.env.BASE_URL || "http://localhost:3000";
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", userDataDir: fs.mkdtempSync(path.join(os.tmpdir(), "es-c2-")) });
const ctx = await b.createBrowserContext();
const p = await ctx.newPage(); await p.setViewport({ width: 1366, height: 860 });
const cdp = await p.createCDPSession(); await cdp.send("Page.setDownloadBehavior", { behavior: "deny" });
await p.goto(BASE + "/gerador-de-capa-abnt/", { waitUntil: "networkidle0" });
await p.evaluate(() => document.fonts.ready);
await p.screenshot({ path: "../capturas/auditoria/f2-vacia.png" });
await p.click("#btnExemploRapido");
await new Promise((r) => setTimeout(r, 2600));
await p.screenshot({ path: "../capturas/auditoria/f2-escribiendo.png" });
await p.waitForFunction(() => /Exemplo preenchido/.test(document.getElementById("toast").textContent), { timeout: 20000 });
await p.click("#btnPdf");
await new Promise((r) => setTimeout(r, 600));
await p.evaluate(() => document.getElementById("compartilhar").scrollIntoView({ block: "center" }));
await new Promise((r) => setTimeout(r, 150));
await p.screenshot({ path: "../capturas/auditoria/f2-festa.png" });
await b.close();
