import fs from "node:fs"; import os from "node:os"; import path from "node:path";
import puppeteer from "puppeteer-core";
const BASE = process.env.BASE_URL || "http://localhost:3000";
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", userDataDir: fs.mkdtempSync(path.join(os.tmpdir(), "es-po-")) });
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 });
await p.goto(BASE + "/", { waitUntil: "networkidle0" });
await p.evaluate(() => document.fonts.ready);
await new Promise((r) => setTimeout(r, 3300));
await p.screenshot({ path: "../capturas/auditoria/portada-escribiendo.png", clip: undefined });
await new Promise((r) => setTimeout(r, 4000));
await p.screenshot({ path: "../capturas/auditoria/portada-lista.png", clip: undefined });
await p.evaluate(() => document.querySelector("#ferramentas").scrollIntoView());
await p.addStyleTag({ content: ".revelar{opacity:1!important;transform:none!important}" });
await new Promise((r) => setTimeout(r, 800));
await p.screenshot({ path: "../capturas/auditoria/portada-ferramentas.png" });
await b.close();
